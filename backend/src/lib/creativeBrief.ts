/**
 * Один вызов на бандл. Любой сбой → `null`: рендер идёт на дефолтах бренда и
 * НЕ блокируется — то же правило, что у `styleProfile`, и оно не обсуждается.
 * Прослойка, роняющая генерацию из-за недоступной LLM, хуже её отсутствия.
 */
export async function requestCreativeBrief(
  req: CreativeBriefRequest,
): Promise<CreativeBrief | null> {
  const text = await chatCompletion(
    CREATIVE_BRIEF_SYSTEM_PROMPT,
    buildCreativeBriefUserMessage(req),
    // temperature 0: один и тот же бриф обязан давать один и тот же разбор,
    // иначе «повтор идентичен» из DoD Фазы 2 недостижим уже на первом шаге.
    { temperature: 0, maxTokens: 600 },
  );
  if (!text) return null;
  return parseCreativeBrief(text, { campaignPrompt: req.campaignPrompt });
}

/** Разбор ответа модели. Вынесен отдельно — тестируется без сети. */
export function parseCreativeBrief(text: string, ctx: ClampContext): CreativeBrief | null {
  // Модели любят заворачивать JSON в ```-ограду вопреки инструкции.
  const bare = text
    .replace(/^\s*```(?:json)?\s*/i, "")
    .replace(/\s*```\s*$/, "")
    .trim();
  let parsed: unknown;
  try {
    parsed = JSON.parse(bare);
  } catch {
    return null;
  }
  const res = creativeBriefSchema.safeParse(parsed);
  if (!res.success) return null;
  return clampCreativeBrief(res.data, ctx);
}
