export interface CreativeBriefRequest {
  /** Свободный текст менеджера — `Bundle.neuralPrompt`. */
  campaignPrompt: string;
  /** Выбранный пресет типа акции; пусто → "none". */
  presetKey?: string | null;
  brandName: string;
  assetKey: string;
  /**
   * Теги концептов наполненной библиотеки. ПОДСКАЗКА, а не белый список:
   * библиотека необязательна (`D-N7'`), и концепт, которого в ней нет, будет
   * сгенерирован листом декора.
   */
  availableConcepts?: string[];
}

export function buildCreativeBriefUserMessage(req: CreativeBriefRequest): string {
  const concepts = req.availableConcepts?.length
    ? req.availableConcepts.join(", ")
    : "(none — will be generated)";
  return [
    `Campaign preset: ${req.presetKey?.trim() || "none"}`,
    `Campaign brief: ${req.campaignPrompt.trim() || "(empty)"}`,
    `Brand: ${req.brandName}`,
    `Asset type: ${req.assetKey}`,
    `Decor already available for this brand: ${concepts}`,
  ].join("\n\n");
}

