/** Концепт декора: короткое родовое существительное, только латиница. */
export const CONCEPT_RE = /^[a-z_]{2,20}$/;
/** Не больше двух надписей на кадр: слоты `left-fill` и `held`. */
export const MAX_CAPTIONS = 2;
export const MAX_DECOR_CONCEPTS = 6;

export const creativeBriefSchema = z.object({
  offer: z.object({
    kind: z.enum(OFFER_KINDS),
    headline: z.string().max(40).nullable(),
    amount: z.string().max(40).nullable(),
    extras: z.array(z.string().max(60)).max(3).default([]),
    cta: z.string().max(30).nullable(),
  }),
  mood: z.enum(MOODS),
  season: z.enum(SEASONS).nullable(),
  decorConcepts: z.array(z.string()).max(MAX_DECOR_CONCEPTS).default([]),
  paletteHint: z.string().max(60).nullable(),
  lightMood: z.string().max(80),
  captions: z.array(z.string().max(MAX_TOKEN_CHARS)).max(MAX_CAPTIONS).default([]),
  confidence: z.object({ offer: z.number(), scene: z.number() }),
});

export type CreativeBrief = z.infer<typeof creativeBriefSchema>;

