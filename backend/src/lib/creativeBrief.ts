/**
 * Слова, которыми `lightMood` описывать сцену не должен: это объекты и
 * раскладка, а не свет. Нарушение здесь дороже, чем кажется — `lightMood`
 * попадает в промпт генеративного слоя, а тот обязан остаться БЕЗ объектов,
 * иначе кейинг `alpha = f(яркость)` (`D-N6`) превратит нарисованную монету в
 * полупрозрачный призрак.
 */
const LIGHT_MOOD_BANNED = [
  "coin", "chip", "banknote", "money", "cash", "card", "dice", "star", "gift",
  "crown", "diamond", "bar", "petal", "leaf", "snowflake", "confetti", "balloon",
  "character", "person", "man", "woman", "girl", "boy", "dog", "cat", "animal",
  "mascot", "logo", "text", "letter", "number", "sign", "banner", "frame",
  "left", "right", "centre", "center", "top", "bottom", "corner",
];

/**
 * Контекст клампа — только промпт кампании.
 *
 * Списка доступных концептов здесь намеренно НЕТ: библиотека декора
 * необязательна (`D-N7'`), и концепт, которого в ней нет, не выбрасывается, а
 * уходит в генерацию листа декора (`D-N9'`). Белым списком библиотека была бы
 * ровно до первой сезонной акции.
 */
export interface ClampContext {
  campaignPrompt: string;
}

/** Буквы и цифры подряд, в верхнем регистре — для сравнения надписи с брифом. */
function alnumUpper(s: string): string {
  return s.toUpperCase().replace(/[^A-Z0-9А-ЯЁ]+/g, "");
}

/**
 * Надпись законна, только если она реально прозвучала в брифе (правило 2).
 * Сравнение по буквенно-цифровому «скелету»: «+50 FREE SPINS» в брифе и
 * надпись «50 FREE SPINS» — это одно и то же, а вот «BIG WIN» из воздуха — нет.
 */
export function captionAppearsInBrief(caption: string, brief: string): boolean {
  const c = alnumUpper(caption);
  if (c.length === 0) return false;
  const b = alnumUpper(brief);
  if (b.includes(c)) return true;
  // Либо каждое слово надписи встречается в брифе по отдельности.
  const words = caption.split(/\s+/).map(alnumUpper).filter((w) => w.length > 1);
  return words.length > 0 && words.every((w) => b.includes(w));
}

/**
 * Сумма законна, только если её цифры реально есть в брифе.
 *
 * Правило 1 системного промпта запрещает выдумывать сумму, но одной
 * инструкции мало: это самая дорогая из возможных ошибок — «500 000$»,
 * которых не было в кампании, уходит живому клиенту в письме. Надписи мы
 * уже проверяем по брифу; сумма заслуживает того же, и даже больше.
 *
 * Сравниваются ЦИФРЫ, а не строка целиком: «500 000$» в брифе и «500000$»
 * в ответе — одно и то же, а «1 000 000$» — уже нет.
 */
export function amountAppearsInBrief(amount: string, brief: string): boolean {
  const digits = amount.replace(/\D+/g, "");
  if (digits.length === 0) return true; // «up to 100 free spins» без числа в сумме
  return brief.replace(/\D+/g, "").includes(digits);
}

export function lightMoodNamesObject(lightMood: string, decorConcepts: string[]): boolean {
  const low = ` ${lightMood.toLowerCase().replace(/[^a-z ]+/g, " ")} `;
  const banned = [...LIGHT_MOOD_BANNED, ...decorConcepts.map((c) => c.replace(/_/g, " "))];
  return banned.some((w) => low.includes(` ${w} `) || low.includes(` ${w}s `));
}

/**
 * Приведение ответа модели к тому, что система готова исполнить. Схема
 * защищает от неверных ТИПОВ, кламп — от правдоподобной выдумки внутри
 * допустимых типов. Тот же приём, что в работающем `clampStyleProfile`.
 */
export function clampCreativeBrief(brief: CreativeBrief, ctx: ClampContext): CreativeBrief {
  const decorConcepts = [...new Set(brief.decorConcepts.map((c) => c.trim().toLowerCase()))]
    .filter((c) => CONCEPT_RE.test(c))
    .slice(0, MAX_DECOR_CONCEPTS);

  const captions = brief.captions
    .map((c) => c.trim().toUpperCase().replace(/\s+/g, " "))
    .filter((c) => c.length > 0 && c.length <= MAX_TOKEN_CHARS)
    .filter((c) => captionAppearsInBrief(c, ctx.campaignPrompt))
    .slice(0, MAX_CAPTIONS);

  const lightMood = lightMoodNamesObject(brief.lightMood, decorConcepts)
    ? ""
    : brief.lightMood.trim();

  // Сумма, которой не было в брифе, обнуляется вместе с ведущей строкой:
  // «UP TO» без числа под ним — это не оффер, а обрывок.
  const amountOk =
    brief.offer.amount === null || amountAppearsInBrief(brief.offer.amount, ctx.campaignPrompt);
  // D-N16: headline, extras и cta — дыра того же рода, что и сумма (D-N13).
  // Выдуманный «+50 FREE SPINS» уходит в `textOverlay.lines` письма ровно так
  // же, как выдуманные «500 000$». Правило одно на весь текст оффера: строка
  // законна, только если прозвучала в брифе; пустое поле заполняет конфиг
  // бренда, а не фантазия модели.
  const headlineOk =
    amountOk &&
    brief.offer.headline !== null &&
    captionAppearsInBrief(brief.offer.headline, ctx.campaignPrompt);
  const ctaOk =
    brief.offer.cta !== null && captionAppearsInBrief(brief.offer.cta, ctx.campaignPrompt);
  const offer = {
    ...brief.offer,
    amount: amountOk ? brief.offer.amount : null,
    headline: headlineOk ? brief.offer.headline : null,
    extras: brief.offer.extras.filter((e) => captionAppearsInBrief(e, ctx.campaignPrompt)),
    cta: ctaOk ? brief.offer.cta : null,
  };

  return {
    ...brief,
    offer,
    decorConcepts,
    captions,
    lightMood,
    // Числа уверенности приходят от модели и ни на что не влияют напрямую —
    // зажимаем в 0..1, чтобы они не портили логи и превью.
    confidence: {
      offer: clamp01(brief.confidence.offer),
      scene: clamp01(brief.confidence.scene),
    },
  };
}

function clamp01(v: number): number {
  if (!Number.isFinite(v)) return 0;
  return Math.min(1, Math.max(0, v));
}

